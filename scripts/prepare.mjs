// Records this plugin's absolute location so the server can load mupdf from its node_modules.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
writeFileSync(
  path.join(root, "server", "plugin-root.generated.ts"),
  `// Generated by scripts/prepare.mjs. Do not edit.\nexport const PLUGIN_ROOT = ${JSON.stringify(root)};\n`,
);
